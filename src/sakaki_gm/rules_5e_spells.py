def ensure_5e_spells(db, *, commit: bool = False) -> dict:
    """Insert missing stock 5e spells. Does not overwrite existing names."""
    from sakaki_gm.spell_db import upsert_campaign_spell_if_missing

    added_ids = []
    skipped = 0
    for entry in DEFAULT_5E_SPELLS:
        result = upsert_campaign_spell_if_missing(db, entry, commit=False)
        if result is None:
            skipped += 1
        else:
            added_ids.append(result)
    if commit and added_ids:
        db.commit()
    return {"added": len(added_ids), "skipped": skipped, "ids": added_ids}
